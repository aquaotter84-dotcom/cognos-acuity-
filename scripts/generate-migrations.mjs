#!/usr/bin/env node
/**
 * scripts/generate-migrations.mjs
 *
 * Emits migrations/NNNN_<name>.sql from the single source of truth:
 * server/db/schema.js (PHASE_SCHEMAS).
 *
 * The running server applies the same statements lazily at boot (server/db.js
 * concatenates every additive PHASE schema onto the base SCHEMA), so these
 * files exist for operators who want the DDL in reviewable, versioned form —
 * not as a second schema definition. Regenerate after any schema change:
 *
 *     node scripts/generate-migrations.mjs
 *
 * Every statement is additive and idempotent (CREATE TABLE IF NOT EXISTS /
 * CREATE INDEX IF NOT EXISTS / ALTER TABLE ... ADD COLUMN IF NOT EXISTS), so
 * re-running a migration against a populated database changes nothing.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PHASE_SCHEMAS } from "../server/db/schema.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const migrationsDir = join(root, "migrations");

const HEADER = (m) => `-- ============================================================================
-- ${m.id} — ${m.name} (Phase ${m.phase})
-- ============================================================================
-- Generated by scripts/generate-migrations.mjs from server/db/schema.js.
-- Do not edit by hand: edit the source of truth and regenerate.
--
-- ADDITIVE ONLY. This migration creates new tables and indexes and adds
-- columns to existing ones. It never drops, renames, truncates or rewrites
-- existing tables, so existing rows keep their semantics. Every statement is
-- idempotent and safe to re-run.
--
-- Apply with:   node scripts/migrate.mjs
-- (The server also applies these same statements at boot, so running this
--  script is optional — it exists for review and for controlled rollouts.)
`;

mkdirSync(migrationsDir, { recursive: true });

let written = 0;
for (const migration of PHASE_SCHEMAS) {
  const file = join(migrationsDir, `${migration.id}_${migration.name}.sql`);
  const body = HEADER(migration) + migration.sql.trim() + "\n";
  writeFileSync(file, body, "utf8");
  console.log(`wrote migrations/${migration.id}_${migration.name}.sql (${body.length} bytes)`);
  written++;
}

console.log(`\n${written} migration file(s) generated from ${PHASE_SCHEMAS.length} schema block(s).`);
